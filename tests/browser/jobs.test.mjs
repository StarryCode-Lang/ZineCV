import { test } from "node:test";
import assert from "node:assert/strict";
import { resolve } from "node:path";
import { createBrowserTestServer, listenForBrowserTestServer, launchBrowserTestChromium } from "./fixtures/browser-test-server.mjs";

test("job materials retry exact writes, retain revision evidence and prepare only explicitly selected facts without a model", { timeout: 60_000 }, async () => {
  const server = await createBrowserTestServer(resolve(import.meta.dirname, "../.."));
  await listenForBrowserTestServer(server);
  const browser = await launchBrowserTestChromium({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  try {
    const page = await context.newPage(), errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/__zinecv_browser_test_page.html`);
    await page.evaluate(() => import("/tests/browser/fixtures/mount-job-workspace.tsx"));
    await page.getByRole("button", { name: "岗位定制", exact: true }).click();
    await page.getByRole("dialog").waitFor();
    await page.getByLabel("岗位名称", { exact: true }).fill("Frontend Engineer");
    await page.getByLabel("公司", { exact: true }).fill("Synthetic Company");
    await page.getByLabel("职位描述", { exact: true }).fill("TypeScript\nSQL experience");
    await page.getByRole("button", { name: "保存岗位材料", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "岗位保存回执丢失" }).waitFor();
    assert.equal(await page.getByLabel("岗位名称", { exact: true }).inputValue(), "Frontend Engineer");
    await page.getByRole("button", { name: "重试上次操作" }).click();
    await page.getByRole("status").filter({ hasText: "已保存材料修订 1" }).waitFor();
    const commands = await page.evaluate(() => window.jobFixture.saveCommands);
    assert.equal(commands.length, 2); assert.equal(commands[0], commands[1]);
    await page.getByLabel("新岗位分支名称").fill("Frontend application");
    await page.getByRole("button", { name: "从当前保存状态创建分支" }).click();
    await page.getByLabel("关联岗位分支").selectOption("job-branch");
    await page.getByRole("button", { name: "关联当前材料修订" }).click();
    await page.getByRole("status").filter({ hasText: "岗位材料已关联" }).waitFor();
    await page.getByRole("checkbox").check();
    assert.match(await page.locator("table").textContent(), /TypeScript/);
    assert.match(await page.locator("table").textContent(), /保留缺口/);
    await page.getByRole("button", { name: "将所选事实与岗位送入助手草稿" }).click();
    const prepared = await page.evaluate(() => ({ requests: window.jobFixture.requests, modelCalls: window.jobFixture.modelCalls }));
    assert.equal(prepared.modelCalls, 0);
    assert.deepEqual(prepared.requests[0].referenceIds, ["entry:projects:project-fact"]);
    assert.equal(prepared.requests[0].material.revision, 1);
    const composer = page.getByRole("textbox", { name: "给 Re:me 助手发送消息" });
    await composer.waitFor();
    assert.match(await composer.inputValue(), /Frontend Engineer.*岗位材料修订 1/);
    await page.getByText(/本轮将发送 2 个引用/).click();
    const sentContext = await page.locator(".agent-context-disclosure pre").textContent();
    assert.match(sentContext, /TypeScript/);
    assert.match(sentContext, /SQL experience/);
    assert.match(sentContext, /project-fact/);
    assert.equal(await page.getByRole("button", { name: /移除引用/ }).count(), 2);
    assert.equal(await page.evaluate(() => window.jobFixture.modelCalls), 0);
    await composer.fill("保留用户已写的草稿");
    await page.getByRole("button", { name: "最小化到 Bot" }).click();
    await page.getByRole("button", { name: "岗位定制", exact: true }).click();
    await page.getByRole("dialog").waitFor().catch(async reason => {
      assert.fail(`${reason.message}: ${JSON.stringify(await page.evaluate(() => ({ body: document.body.innerText, dialogs: document.querySelectorAll("dialog").length, fixture: window.jobFixture })))}`);
    });
    await page.getByLabel("职位描述", { exact: true }).fill("TypeScript\nSQL experience\nAccessibility");
    await page.getByRole("button", { name: "保存岗位材料", exact: true }).click();
    await page.getByText("材料已更新，请重新核对").waitFor();
    await page.getByText("查看当时依据", { exact: true }).click();
    assert.equal(await page.getByRole("dialog").locator("pre").textContent(), "TypeScript\nSQL experience");
    await page.getByRole("checkbox").check();
    await page.getByRole("button", { name: "将所选事实与岗位送入助手草稿" }).click();
    await composer.waitFor();
    assert.match(await composer.inputValue(), /保留用户已写的草稿/);
    assert.match(await composer.inputValue(), /岗位材料修订 2/);
    await page.getByText(/本轮将发送 2 个引用/).click();
    assert.match(await page.locator(".agent-context-disclosure pre").textContent(), /Accessibility/);
    assert.equal(await page.getByRole("button", { name: /移除引用/ }).count(), 2);
    assert.equal(await page.evaluate(() => window.jobFixture.requests[1].material.revision), 2);
    assert.equal(await page.evaluate(() => window.jobFixture.modelCalls), 0);
    await page.getByRole("button", { name: "最小化到 Bot" }).click();
    await page.getByRole("button", { name: "岗位定制", exact: true }).click();
    await page.getByRole("dialog").waitFor();
    await page.getByLabel("公司", { exact: true }).fill("unsaved change");
    await page.getByRole("button", { name: "关闭", exact: true }).click();
    await page.getByRole("button", { name: "返回核对", exact: true }).click();
    assert.equal(await page.getByLabel("公司", { exact: true }).inputValue(), "unsaved change");
    assert.equal(await page.evaluate(() => window.jobFixture.materials[0].company), "Synthetic Company");
    assert.deepEqual(errors, []);
  } finally { await context.close(); await browser.close(); await server.close(); }
});
